 d=await json(`/api/documents/${id}/restore`,{method:'POST'});assert.equal(d.published,false);assert.equal(d.deletedAt,null);assert.ok(d.markdown.includes('尚未发布的草稿标记'));
 assert.equal((await request(path)).status,404);
 for(const route of ['/admin/','/api/documents'])assert.equal((await request(route)).headers.get('cache-control'),'no-store');
