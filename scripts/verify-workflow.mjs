const cookie=login.headers.get('set-cookie').split(';')[0], csrf=(await login.json()).csrf;
const request=async(route,options={})=>{const isForm=options.body instanceof FormData;return fetch(base+route,{...options,headers:{cookie,'X-CSRF-Token':csrf,...(options.body&&!isForm?{'Content-Type':'application/json'}:{}),...options.headers},body:options.body&&!isForm?JSON.stringify(options.body):options.body,signal:AbortSignal.timeout(15000)})};
const json=async(route,options)=>{const r=await request(route,options);assert.ok(r.ok,`${route}: ${r.status}`);return r.json()};
const waitJob=async(id)=>{for(let i=0;i<60;i++){const j=await json('/api/jobs/'+id);if(j.status==='failed')throw new Error(j.log);if(j.status==='success')return j;await new Promise(resolve=>setTimeout(resolve,500))}throw new Error('发布任务超时')};
