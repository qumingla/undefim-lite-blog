 assert.equal(revisions.length,1);
 const revision=await json(`/api/documents/${id}/revisions/${revisions[0].id}`);
 assert.equal(revision.data.markdown,original);
 d=await json(`/api/documents/${id}/revisions/${revisions[0].id}/restore`,{method:'POST'});
 assert.equal(d.markdown,original);
 await waitJob((await json(`/api/documents/${id}/publish`,{method:'POST'})).job);
 d=await json('/api/documents/'+id);assert.equal(d.published,true);
